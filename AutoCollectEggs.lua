                end
            end
        end
    end

    -- Convert decoded bytes to string in fast chunks
    local _chunks = {}
    local _chunkLimit = 4096
    local _total = #_out
    for _idx = 1, _total, _chunkLimit do
        local _end = math.min(_idx + _chunkLimit - 1, _total)
        local _t = table.create(_end - _idx + 1)
        for _m = _idx, _end do
