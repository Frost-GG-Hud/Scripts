        local _c2 = _B64MAP[_inp:sub(_i+1, _i+1)] or 0
        local _c3 = _B64MAP[_inp:sub(_i+2, _i+2)] or 0
        local _c4 = _B64MAP[_inp:sub(_i+3, _i+3)] or 0

