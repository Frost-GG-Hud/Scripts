                        _idx = _idx + 1
                    elseif _sym == 16 then
                        local _rep = _getBits(2) + 3
                        local _last = _lens[_idx - 1]
                        for _ = 1, _rep do _lens[_idx] = _last _idx = _idx + 1 end
                    elseif _sym == 17 then
